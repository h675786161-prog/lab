def upsert(name, keys, content, priority=145, constant=False, insertion_order=None):
    for e in entries:
        if e.get('name') == name:
            e.update({
                'keys': keys,
                'content': content,
                'priority': priority,
                'constant': constant,
                'enabled': True,
                'case_sensitive': False,
                'selective': False,
                'secondary_keys': [],
                'position': 'before_char',
            })
            if insertion_order is not None:
                e['insertion_order'] = insertion_order
            return e
    new_id = max(int(e.get('id', 0)) for e in entries) + 1
    e = {
        'keys': keys,
        'content': content,
        'extensions': {},
        'enabled': True,
        'insertion_order': insertion_order if insertion_order is not None else priority,
        'case_sensitive': False,
        'name': name,
        'priority': priority,
        'id': new_id,
        'comment': name,
        'selective': False,
        'secondary_keys': [],
        'constant': constant,
        'position': 'before_char',
    }
    entries.append(e)
    return e

