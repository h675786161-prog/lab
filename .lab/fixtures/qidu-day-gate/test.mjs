import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const root='.lab/fixtures/qidu-day-gate';
const card=JSON.parse(fs.readFileSync(root+'/Qidu-v0.4.43-decision-boundary.json','utf8'));
const code=fs.readFileSync(root+'/day-gate.js','utf8');
const source=card.data.character_book.entries;
let current=null;
const callbacks=new Map();
const emitter={on:(n,f)=>callbacks.set(n,f),makeFirst:()=>{},removeListener:(n,f)=>{if(callbacks.get(n)===f)callbacks.delete(n)}};
const context={chat:[{is_user:false,is_system:false,mes:'当前存档'}],eventTypes:{WORLDINFO_ENTRIES_LOADED:'worldinfo_entries_loaded'},eventSource:emitter};
const host={SillyTavern:{getContext:()=>context}};
const window={parent:host,addEventListener:()=>{},removeEventListener:()=>{}};
vm.runInNewContext(code,{window,console,getVariables:()=>({stat_data:current})},{timeout:1000});
const nativeEntries=()=>source.map(e=>({uid:e.id,comment:e.comment,content:e.content,disable:!e.enabled,constant:e.constant}));
const checks=[];
for(let day=7;day>=1;day--){
 current={schema:'f7d_textloop_0.4',day,route:'central',morning_flags:{day6_saiham:day<6},intel_flags:{}};
 const p={characterLore:nativeEntries(),globalLore:[],chatLore:[],personaLore:[]};
 callbacks.get('worldinfo_entries_loaded')(p);
 const days=p.characterLore.filter(e=>e.uid>=10&&e.uid<=17).map(e=>e.uid);
 const expected=day===1?[16,17]:[17-day];
 assert.deepEqual(days,expected);
 assert.equal(p.characterLore.some(e=>e.uid===18),false);
 assert.equal(p.characterLore.some(e=>e.uid===64),day>=6);
 assert.equal(p.characterLore.some(e=>e.uid===33),day<=5);
 checks.push({day,dayEntries:days,saiham:p.characterLore.some(e=>e.uid===64)});
}
current=null;
const p={characterLore:nativeEntries()};
callbacks.get('worldinfo_entries_loaded')(p);
assert.equal(p.characterLore.some(e=>e.comment.startsWith('[F7D_GATE:')),false);
current={schema:'f7d_textloop_0.4',day:7,route:'central',morning_flags:{},intel_flags:{}};
const rollback={characterLore:nativeEntries()};
callbacks.get('worldinfo_entries_loaded')(rollback);
assert.deepEqual(rollback.characterLore.filter(e=>e.uid>=10&&e.uid<=17).map(e=>e.uid),[10]);
host.f7dDayGate.dispose();
assert.equal(callbacks.size,0);
fs.writeFileSync(root+'/gate-tests.json',JSON.stringify({checks,noState:'passed',rollback:'passed',unload:'passed'},null,2));
console.log('gate-tests passed',JSON.stringify(checks));
